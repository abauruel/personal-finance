export const getDashboardMessages = (locale: Locale) => DASHBOARD_MESSAGES[locale] ?? DASHBOARD_MESSAGES['en-US'];

export const getDashboardMonthLabel = (value: string, locale: Locale) => {
  const [yearPart, monthPart] = value.split('-');
  const year = Number.parseInt(yearPart, 10) || 2024;
  const monthIndex = Math.max(0, (Number.parseInt(monthPart, 10) || 1) - 1);

  return new Intl.DateTimeFormat(locale, { month: 'short' }).format(new Date(year, monthIndex, 1));
};

export const getDashboardAccountTypeLabel = (type: string, locale: Locale) => {
  const messages = getDashboardMessages(locale);
  return messages.accountTypes[type.toUpperCase()] || type;
};

export const getDashboardFilterStatuses = (locale: Locale) => {
  const messages = getDashboardMessages(locale);
  return FILTER_STATUS_ORDER.map((status) => ({ value: status, label: messages.filterModal.statusOptions[status] }));
};